function inventoryId(brand, name) {
  return ((brand && brand !== 'Unknown' ? brand + ' ' : '') + name).toLowerCase()
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

