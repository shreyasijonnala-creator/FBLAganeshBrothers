function inventoryId(brand, name) {
  return ((brand && !name.startsWith(brand) ? brand + ' ' : '') + name).toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

